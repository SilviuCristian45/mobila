import type { CatalogItem } from '@/domain';

type Range = readonly [number, number];
type ParamSpec = CatalogItem['paramSpecs'][string];

const provenance = { origin: 'original', license: 'proprietar-proiect' } as const;

const count = (min: number, max: number, def: number): ParamSpec => ({
  type: 'number',
  min,
  max,
  step: 1,
  default: def,
  unit: 'count',
});
const mm = (min: number, max: number, step: number, def: number): ParamSpec => ({
  type: 'number',
  min,
  max,
  step,
  default: def,
  unit: 'mm',
});
const oneOf = (options: string[], def: string = options[0]!): ParamSpec => ({
  type: 'enum',
  options,
  default: def,
});
const flag = (def: boolean): ParamSpec => ({ type: 'bool', default: def });

interface Def {
  id: string;
  category: string;
  kind: CatalogItem['kind'];
  name: string;
  /** lățime × adâncime × înălțime (mm) */
  size: readonly [number, number, number];
  limits: readonly [Range, Range, Range];
  mounting?: CatalogItem['mounting'];
  elevation?: number;
  recipe: string;
  params?: Record<string, ParamSpec>;
  color: string;
  /** preț demonstrativ, în RON */
  price: number;
  tags?: string[];
}

function item(d: Def): CatalogItem {
  const [w, dp, h] = d.size;
  const [lw, ld, lh] = d.limits;
  return {
    id: d.id,
    version: 1,
    kind: d.kind,
    category: d.category,
    name: { ro: d.name },
    defaultSize: { widthMm: w, depthMm: dp, heightMm: h },
    sizeLimits: {
      widthMm: { min: lw[0], max: lw[1] },
      depthMm: { min: ld[0], max: ld[1] },
      heightMm: { min: lh[0], max: lh[1] },
    },
    mounting: d.mounting ?? 'floor',
    defaultElevationMm: d.elevation ?? 0,
    recipe: { id: d.recipe, version: 1 },
    paramSpecs: d.params ?? {},
    defaultColorHex: d.color,
    reference: {
      priceMinor: Math.round(d.price * 100),
      currency: 'RON',
      vatIncluded: true,
      origin: 'demo',
    },
    ...(d.tags ? { tags: d.tags } : {}),
    provenance,
  };
}

const frontParams = (fronts: [number, number, number], type = 'doors') => ({
  fronts: count(fronts[0], fronts[1], fronts[2]),
  frontType: oneOf(['doors', 'drawers', 'open'], type),
  handles: flag(true),
});

